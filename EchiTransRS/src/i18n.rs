pub const INTERFACE_CHOICES: &[(&str, &str)] = &[
    ("system", "System / Windows"),
    ("zh-Hant", "繁體中文"),
    ("zh-Hans", "简体中文"),
    ("en", "English"),
    ("ja", "日本語"),
    ("ko", "한국어"),
    ("fr", "Français"),
    ("de", "Deutsch"),
    ("es", "Español"),
    ("pt", "Português"),
    ("ru", "Русский"),
];
pub fn is_interface_preference(tag: &str) -> bool { INTERFACE_CHOICES.iter().any(|(c,_)| *c == tag) }
/// 在執行期解析「system」，切換 UI 設定立即生效。未知 Windows 語系以英文作為回退。
pub fn resolve(preference: &str, system_tag: &str) -> &'static str {
    let tag = if preference == "system" { system_tag } else { preference };
    let code = tag.to_ascii_lowercase().replace('_', "-");
    if code.starts_with("zh-") || code == "zh" {
        if code.contains("hant") || code.contains("tw") || code.contains("hk") || code.contains("mo") { "zh-Hant" }
        else { "zh-Hans" }
    } else if code == "ja" || code.starts_with("ja-") { "ja" }
    else if code == "ko" || code.starts_with("ko-") { "ko" }
    else if code == "fr" || code.starts_with("fr-") { "fr" }
    else if code == "de" || code.starts_with("de-") { "de" }
    else if code == "es" || code.starts_with("es-") { "es" }
    else if code == "pt" || code.starts_with("pt-") { "pt" }
    else if code == "ru" || code.starts_with("ru-") { "ru" }
    else { "en" }
}
pub fn tr(locale: &str, key: Key) -> &'static str {
    let dict = match locale {
        "en" => &EN,
        "zh-Hant" => &ZH_HANT,
        "zh-Hans" => &ZH_HANS,
        "ja" => &JA,
        "ko" => &KO,
        "fr" => &FR,
        "de" => &DE,
        "es" => &ES,
        "pt" => &PT,
        "ru" => &RU,
        _ => &EN,
    };
    dict[key as usize]
}
/// Windows API 回傳 MUI 語言優先序的第一項，例如 zh-TW，而非地區數字日期格式。
pub fn windows_display_locale() -> String {
    #[cfg(windows)] {
        #[link(name = "kernel32")]
        extern "system" {
            fn GetUserPreferredUILanguages(flags: u32, num: *mut u32, languages: *mut u16, length: *mut u32) -> i32;
        }
        const MUI_LANGUAGE_NAME: u32 = 0x8;
        let mut count = 0u32;
        let mut len = 0u32;
        unsafe {
            let _ = GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut count, std::ptr::null_mut(), &mut len);
            if (2..=4096).contains(&len) {
                let mut buffer = vec![0u16; len as usize];
                if GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut count, buffer.as_mut_ptr(), &mut len) != 0 {
                    if let Some(end) = buffer.iter().position(|c| *c == 0) {
                        if end > 0 { if let Ok(s) = String::from_utf16(&buffer[..end]) { return s; } }
                    }
                }
            }
        }
    }
    std::env::var("LANG").unwrap_or_else(|_| "en-US".into())
}
